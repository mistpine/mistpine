/**
 * Resolves `mistpine.theme.json` into `palette/mistpine.json` with the resolver
 * of the themes app (https://themes.utimura.io), so every value matches what the
 * designer shows. Needs a local checkout of the app with its dependencies installed:
 *
 *   THEMES_DIR=../themes pnpm sync
 */
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import type { Entry, Spec } from "./lib/spec.ts";

const root = resolve(import.meta.dirname, "..");
const themesDir = resolve(process.env.THEMES_DIR ?? join(root, "..", "themes"));

type Expr = string | { mix: [Expr, Expr, number] } | { shade: [Expr, number] };
interface ThemesApi {
  parseTheme(value: unknown): { palette: Record<string, string> } | null;
  resolveTheme(theme: unknown): {
    colors: Record<string, string>;
    styles: Record<string, Record<string, boolean>>;
    broken: string[];
  };
  effectiveExpr(theme: unknown, id: string): Expr | undefined;
  describeExpr(expr: Expr): string;
  TOKENS: { id: string; group: string; key: string }[];
  SYNTAX_KEYS: readonly string[];
  PALETTE_KEYS: readonly string[];
}

async function loadThemes(): Promise<ThemesApi> {
  const tmp = mkdtempSync(join(tmpdir(), "mistpine-sync-"));
  try {
    const entry = join(tmp, "entry.ts");
    writeFileSync(
      entry,
      [
        'export { parseTheme } from "@/model/theme";',
        'export { resolveTheme, effectiveExpr, describeExpr } from "@/model/resolve";',
        'export { TOKENS, SYNTAX_KEYS } from "@/model/tokens";',
        'export { PALETTE_KEYS } from "@/model/palette";',
      ].join("\n"),
    );
    const out = join(tmp, "themes.mjs");
    execFileSync(
      join(themesDir, "node_modules", ".bin", "esbuild"),
      [
        entry,
        "--bundle",
        "--platform=node",
        "--format=esm",
        `--alias:@=${join(themesDir, "src")}`,
        `--outfile=${out}`,
        "--log-level=warning",
      ],
      { stdio: "inherit" },
    );
    return (await import(pathToFileURL(out).href)) as ThemesApi;
  } finally {
    rmSync(tmp, { recursive: true, force: true });
  }
}

const api = await loadThemes();
const theme = api.parseTheme(JSON.parse(readFileSync(join(root, "mistpine.theme.json"), "utf8")));
if (!theme) throw new Error("mistpine.theme.json is not a valid theme");
const resolved = api.resolveTheme(theme);
if (resolved.broken.length) throw new Error(`reference cycles: ${resolved.broken.join(", ")}`);

// Neutrals dark to light (the app lists fg3 first), then accents and brights.
const order = [
  ...["bg0", "bg1", "bg2", "bg3", "bg4", "fg0", "fg1", "fg2", "fg3"],
  ...api.PALETTE_KEYS.filter((k) => !/^(bg|fg)\d$/.test(k)),
];
const palette = Object.fromEntries(order.map((k) => [k, theme.palette[k] as string]));
const byHex = new Map<string, string>();
for (const [key, hex] of Object.entries(palette)) {
  if (byHex.has(hex)) throw new Error(`${key} and ${byHex.get(hex)} share ${hex}`);
  byHex.set(hex, key);
}

/** Follows `@token` links down to the palette swatch (or derivation) a token comes from. */
function origin(expr: Expr | undefined): Pick<Entry, "ref" | "derived"> {
  if (expr === undefined) return {};
  if (typeof expr !== "string") return { derived: api.describeExpr(expr) };
  if (expr.startsWith("$")) return { ref: expr.slice(1) };
  if (expr.startsWith("@")) return origin(api.effectiveExpr(theme, expr.slice(1)));
  const key = byHex.get(expr);
  return key ? { ref: key } : {};
}

function entry(id: string, extra: Record<string, boolean> = {}): Entry {
  const hex = resolved.colors[id];
  if (!hex) throw new Error(`unknown token ${id}`);
  return { hex, ...origin(api.effectiveExpr(theme, id)), ...extra };
}

const group = (name: string) => api.TOKENS.filter((t) => t.group === name);

const spec: Spec = {
  $comment: "Generated by scripts/sync.ts from mistpine.theme.json. Do not edit by hand.",
  name: "mistpine",
  variant: "dark",
  palette,
  terminal: Object.fromEntries(
    group("terminal")
      .filter((t) => !t.key.startsWith("ansi"))
      .map((t) => [t.key, entry(t.id)]),
  ),
  ansi: Array.from({ length: 16 }, (_, i) => entry(`terminal.ansi${i}`)),
  syntax: Object.fromEntries(
    api.SYNTAX_KEYS.map((k) => [k, entry(`syntax.${k}`, resolved.styles[k] ?? {})]),
  ),
  ui: Object.fromEntries(group("ui").map((t) => [t.key, entry(t.id)])),
};

writeFileSync(join(root, "palette", "mistpine.json"), `${JSON.stringify(spec, null, 2)}\n`);
console.log(`palette/mistpine.json: resolved with ${themesDir}`);
