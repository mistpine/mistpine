/** Palette files for other tools, all derived from `palette/mistpine.json`. */
import type { Entry, Spec } from "./spec.ts";

const HEADER = "mistpine: generated by scripts/build.ts from palette/mistpine.json";
const kebab = (s: string) => s.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();
const groups = (spec: Spec) =>
  [
    ["terminal", spec.terminal],
    ["syntax", spec.syntax],
    ["ui", spec.ui],
  ] as const;

function variables(spec: Spec): [section: string, name: string, hex: string][] {
  const rows: [string, string, string][] = [];
  for (const [k, hex] of Object.entries(spec.palette)) rows.push(["palette", kebab(k), hex]);
  for (const [group, entries] of groups(spec)) {
    for (const [k, e] of Object.entries(entries)) rows.push([group, `${group}-${kebab(k)}`, e.hex]);
  }
  spec.ansi.forEach((e, i) => {
    rows.push(["ansi", `ansi-${i}`, e.hex]);
  });
  return rows;
}

function sectioned(spec: Spec, line: (name: string, hex: string) => string): string {
  const out: string[] = [];
  let section = "";
  for (const [s, name, hex] of variables(spec)) {
    if (s !== section) {
      if (section) out.push("");
      out.push(`  /* ${s} */`);
      section = s;
    }
    out.push(line(name, hex));
  }
  return out.join("\n");
}

export function css(spec: Spec): string {
  const body = sectioned(spec, (n, hex) => `  --mistpine-${n}: ${hex};`);
  return `/* ${HEADER} */\n:root {\n  color-scheme: ${spec.variant};\n\n${body}\n}\n`;
}

export function scss(spec: Spec): string {
  const body = sectioned(spec, (n, hex) => `$mistpine-${n}: ${hex};`)
    .split("\n")
    .map((l) => l.replace(/^ {2}\/\* (.*) \*\/$/, "// $1").replace(/^ {2}/, ""))
    .join("\n");
  const map = Object.entries(spec.palette)
    .map(([k, hex]) => `  "${kebab(k)}": ${hex},`)
    .join("\n");
  return `// ${HEADER}\n\n${body}\n\n$mistpine-palette: (\n${map}\n);\n`;
}

const luaKey = (k: string) => (/^[A-Za-z_]\w*$/.test(k) ? k : `["${k}"]`);
function luaStyle(e: Entry): string {
  const flags = (["bold", "italic", "underline"] as const)
    .filter((f) => e[f])
    .map((f) => `, ${f} = true`)
    .join("");
  return `{ fg = "${e.hex}"${flags} }`;
}

export function lua(spec: Spec): string {
  const table = (rows: [string, string][]) => rows.map(([k, v]) => `    ${luaKey(k)} = ${v},`);
  const hexes = (entries: Record<string, Entry>) =>
    table(Object.entries(entries).map(([k, e]) => [k, `"${e.hex}"`]));
  const lines = [
    `-- ${HEADER}`,
    "return {",
    `  name = "${spec.name}",`,
    `  variant = "${spec.variant}",`,
    "  palette = {",
    ...table(Object.entries(spec.palette).map(([k, hex]) => [k, `"${hex}"`])),
    "  },",
    "  terminal = {",
    ...hexes(spec.terminal),
    "  },",
    "  -- ansi[1] is color 0 (black), ansi[16] is color 15 (bright white)",
    "  ansi = {",
    ...spec.ansi.map((e, i) => `    "${e.hex}", -- ${i}`),
    "  },",
    "  syntax = {",
    ...table(Object.entries(spec.syntax).map(([k, e]) => [k, luaStyle(e)])),
    "  },",
    "  ui = {",
    ...hexes(spec.ui),
    "  },",
    "}",
  ];
  return `${lines.join("\n")}\n`;
}

/** Darken an sRGB hex by scaling its channels (for base24's "darkest background"). */
function darken(hex: string, factor: number): string {
  const n = Number.parseInt(hex.slice(1), 16);
  const ch = [16, 8, 0].map((s) => Math.round(((n >> s) & 255) * factor));
  return `#${ch.map((c) => c.toString(16).padStart(2, "0")).join("")}`;
}

/** The lightest tone of the identity (light mark's fog): base16 "lightest foreground". */
const LIGHTEST = "#e2e3e7";

/**
 * tinted-theming slots. mistpine's neutral ramp runs bg0 → fg3 (dark to light),
 * so base03 (comments) is fg1 and base05 (text) is fg3.
 */
function base16Slots(spec: Spec): Record<string, string> {
  const p = spec.palette as Record<string, string>;
  const a = spec.ansi.map((e) => e.hex);
  const at = (i: number) => a[i] as string;
  return {
    base00: spec.terminal.background?.hex as string,
    base01: p.bg2 as string,
    base02: spec.ui.selection?.hex as string,
    base03: spec.syntax.comment?.hex as string,
    base04: p.fg2 as string,
    base05: spec.terminal.foreground?.hex as string,
    base06: at(15),
    base07: LIGHTEST,
    base08: p.red as string,
    base09: p.orange as string,
    base0A: p.yellow as string,
    base0B: p.green as string,
    base0C: p.cyan as string,
    base0D: p.blue as string,
    base0E: p.purple as string,
    base0F: p.pink as string,
  };
}

function scheme(spec: Spec, system: string, slots: Record<string, string>): string {
  const rows = Object.entries(slots).map(([k, v]) => `  ${k}: "${v}"`);
  return [
    `# ${HEADER}`,
    `system: "${system}"`,
    `name: "${spec.name}"`,
    `slug: "${spec.name}"`,
    `author: "Luan Utimura (https://github.com/lnutimura/mistpine)"`,
    `variant: "${spec.variant}"`,
    "palette:",
    ...rows,
    "",
  ].join("\n");
}

export const base16 = (spec: Spec) => scheme(spec, "base16", base16Slots(spec));

export function base24(spec: Spec): string {
  const p = spec.palette as Record<string, string>;
  const a = spec.ansi.map((e) => e.hex);
  return scheme(spec, "base24", {
    ...base16Slots(spec),
    base10: p.bg0 as string,
    base11: darken(p.bg0 as string, 0.6),
    base12: a[9] as string,
    base13: a[11] as string,
    base14: a[10] as string,
    base15: a[14] as string,
    base16: a[12] as string,
    base17: a[13] as string,
  });
}
